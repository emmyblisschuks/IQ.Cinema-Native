type Lang = keyof typeof messages;
type Keys = keyof (typeof messages)["en"];

export function t(lang: string, key: string, vars?: Record<string, string | number>): string {
  const dict = messages[(lang as Lang) in messages ? (lang as Lang) : "en"];
  let str = (dict as Record<string, string>)[key] ?? (messages.en as Record<string, string>)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}
